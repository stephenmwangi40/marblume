// Copies the AdMob IDs from ads.json to every place that needs them:
//   www/ads.js (rewarded ad unit IDs for the game), the Android app ID (strings.xml),
//   the iOS app ID (Info.plist) and site-src/app-ads.txt (only once publisherId is set).
// Run by `npm run build:web`.
import fs from 'node:fs';

const cfg = JSON.parse(fs.readFileSync('ads.json', 'utf8'));
const TEST = 'ca-app-pub-3940256099942544';
const testing = [cfg.android.rewarded, cfg.ios.rewarded].some((id) => id.startsWith(TEST + '/'));

fs.writeFileSync('www/ads.js', '// Generated by scripts/ads-config.mjs from ads.json\nwindow.MARBLUME_ADS=' +
  JSON.stringify({ android: cfg.android.rewarded, ios: cfg.ios.rewarded, testing }) + ';\n');

const put = (file, re, value) => {
  const s = fs.readFileSync(file, 'utf8');
  if (!re.test(s)) throw new Error(`${file}: AdMob app ID entry not found`);
  fs.writeFileSync(file, s.replace(re, (m, a, b) => a + value + b));
};
put('android/app/src/main/res/values/strings.xml', /(<string name="admob_app_id">)[^<]*(<\/string>)/, cfg.android.appId);
put('ios/App/App/Info.plist', /(<key>GADApplicationIdentifier<\/key>\s*<string>)[^<]*(<\/string>)/, cfg.ios.appId);

// app-ads.txt tells advertisers which AdMob account may sell ads in this app (Google's line format)
if (/^pub-\d{10,}$/.test(cfg.publisherId)) fs.writeFileSync('site-src/app-ads.txt', `google.com, ${cfg.publisherId}, DIRECT, f08c47fec0942fa0\n`);
else { fs.rmSync('site-src/app-ads.txt', { force: true }); console.warn('ads.json: no publisherId yet, so app-ads.txt is not published.'); }

console.log(`AdMob: ${testing ? 'TEST ads (Google test IDs)' : 'live ad units'} · Android ${cfg.android.appId} · iOS ${cfg.ios.appId}`);
