// Bundles the translations in scripts/i18n/<lang>.json into www/i18n.js (loaded by the game before its own script).
// English is the source text in the game itself, so it has no file. Check coverage with: node scripts/i18n-keys.mjs
import fs from 'node:fs';
import path from 'node:path';
const DIR = 'scripts/i18n', all = {};
for (const f of fs.readdirSync(DIR).filter((f) => f.endsWith('.json')).sort()) all[path.basename(f, '.json')] = JSON.parse(fs.readFileSync(path.join(DIR, f), 'utf8'));
fs.writeFileSync('www/i18n.js', '// Generated by scripts/build-i18n.mjs from scripts/i18n/*.json\nwindow.MARBLUME_I18N=' + JSON.stringify(all) + ';\n');
console.log('www/i18n.js:', Object.entries(all).map(([k, v]) => `${k} ${Object.keys(v).length}`).join(', '));
