import sharp from 'sharp'; import fs from 'node:fs'; import path from 'node:path';
const [dir, prefix, out, cols = 6, tw = 300] = process.argv.slice(2);
const files = fs.readdirSync(dir).filter((f) => f.startsWith(prefix + '-') && f.endsWith('.png')).sort();
const imgs = await Promise.all(files.map(async (f) => { const b = await sharp(path.join(dir, f)).resize({ width: +tw }).toBuffer(); const m = await sharp(b).metadata(); return { b, h: m.height, f }; }));
const C = +cols, rowsH = []; for (let i = 0; i < imgs.length; i += C) rowsH.push(Math.max(...imgs.slice(i, i + C).map((x) => x.h)) + 22);
const H = rowsH.reduce((a, b) => a + b, 0), W = C * (+tw + 10);
const comp = []; let y = 0;
imgs.forEach((im, i) => { const r = Math.floor(i / C); if (i % C === 0 && i) y += rowsH[r - 1];
  comp.push({ input: im.b, left: (i % C) * (+tw + 10), top: y + 20 });
  comp.push({ input: Buffer.from(`<svg width="${tw}" height="20"><text x="2" y="15" font-size="14" font-family="Arial">${im.f.replace(prefix + '-', '').replace('.png', '')}</text></svg>`), left: (i % C) * (+tw + 10), top: y }); });
await sharp({ create: { width: W, height: H, channels: 3, background: '#bbb' } }).composite(comp).png().toFile(out);
console.log(out, files.length);
